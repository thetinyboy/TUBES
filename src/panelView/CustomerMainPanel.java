    private void doSearchCustomer(){
        if(searchCustomerInputTextField.getText().isEmpty())
            return;
            Customer c = cc.search(Integer.parseInt(searchCustomerInputTextField.getText()));
            if(c == null ){
                JOptionPane.showMessageDialog(rootPane, "Customer Tidak Ditemukan");
                return;
            }
            setEditDeleteButtonCustomer(true);
            clearTextCustomer();
            
            namaCustomerInputTextField.setText(c.getNama());
            alamatCustomerInputTextField.setText(c.getAlamat());
            nikCustomerInputTextField.setText(c.getNik());
            notelpCustomerInputTextField.setText(c.getNo_telepon());
            
            idCustomer = c.getId_customer();
    }

