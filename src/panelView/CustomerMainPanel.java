    private void deleteCustomerInputButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteCustomerInputButtonActionPerformed
        clearTextCustomer();
        setEditDeleteButtonCustomer(false);
        setComponentsCustomer(false);
        
        int opsi = JOptionPane.showConfirmDialog(rootPane, "Yakin Ingin Melakukan Hapus?", "Hapus Data", JOptionPane.YES_NO_OPTION);
        if( opsi == JOptionPane.NO_OPTION || opsi == JOptionPane.CLOSED_OPTION){
            idCustomer = -1;
            return;
        }
        
        cc.delete(idCustomer);
        idCustomer = -1;
        showCustomer();
    }//GEN-LAST:event_deleteCustomerInputButtonActionPerformed

    private void saveCustomerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveCustomerButtonActionPerformed
        if(actionCustomer == null)
            return;
        try{
            InputKosongCustomerException();
            NomorTeleponCustomerException();
            int result = JOptionPane.showConfirmDialog(rootPane, "Apakah Anda Yakin Ingin Melakukan " + actionCustomer + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

            if (result != JOptionPane.YES_OPTION) {
                return;
            }
            
            switch(actionCustomer){
            case "Tambah":
                c = new Customer(namaCustomerInputTextField.getText(), notelpCustomerInputTextField.getText(), alamatCustomerInputTextField.getText(), nikCustomerInputTextField.getText());
                cc.insert(c);
                clearTextCustomer();
                setEditDeleteButtonCustomer(false);
                setComponentsCustomer(false);
                break;
            case "Edit":
                c = new Customer(namaCustomerInputTextField.getText(), notelpCustomerInputTextField.getText(), alamatCustomerInputTextField.getText(), nikCustomerInputTextField.getText());
                cc.update(c, idCustomer);
                clearTextCustomer();
                setEditDeleteButtonCustomer(false);
                setComponentsCustomer(false);
                break;
            default:
                break;
        }
        showCustomer();
        actionCustomer = null;
        }catch(KosongException e){
            System.err.println(e);
        }catch(NomorTeleponException e){
            JOptionPane.showMessageDialog(rootPane, e.message());
        };
    }//GEN-LAST:event_saveCustomerButtonActionPerformed


